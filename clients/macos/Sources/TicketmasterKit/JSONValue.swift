import Foundation

/// A minimal, order-preserving-enough representation of an arbitrary JSON value.
///
/// `tm-server`'s wire shapes carry a handful of rich, deeply nested structures (`authority`,
/// `executor`, `verification`, `budget`, `retry`, ...) that this client's vertical slice does not
/// yet need to interpret. Rather than hand-writing a full Swift model for each of them (and
/// having decoding fail the moment the server adds a field), those substructures are decoded
/// into `JSONValue` and carried through opaquely. This keeps `Ticket` decoding honest — it never
/// silently drops or crashes on data it doesn't fully understand — while being explicit that
/// those fields are not yet modeled or rendered.
public enum JSONValue: Codable, Equatable, Sendable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let value = try? container.decode(Bool.self) {
            self = .bool(value)
        } else if let value = try? container.decode(Double.self) {
            self = .number(value)
        } else if let value = try? container.decode(String.self) {
            self = .string(value)
        } else if let value = try? container.decode([JSONValue].self) {
            self = .array(value)
        } else if let value = try? container.decode([String: JSONValue].self) {
            self = .object(value)
        } else {
            throw DecodingError.dataCorruptedError(
                in: container, debugDescription: "Unsupported JSON value"
            )
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .null: try container.encodeNil()
        case .bool(let value): try container.encode(value)
        case .number(let value): try container.encode(value)
        case .string(let value): try container.encode(value)
        case .array(let value): try container.encode(value)
        case .object(let value): try container.encode(value)
        }
    }
}
